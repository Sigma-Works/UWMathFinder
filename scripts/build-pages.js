#!/usr/bin/env node
/**
 * build-pages.js — generate static, search-engine-friendly pages.
 *
 * The main site renders everything with JavaScript, which search engines index
 * poorly. This script writes plain HTML pages (with schema.org JSON-LD) so a
 * search like "UW Math 126 Winter 2024 final" can land on uwmathfinder.com:
 *
 *   courses/index.html                           → all courses
 *   courses/math-126/index.html                  → one page per course (Course)
 *   courses/math-126/exams/final-winter-2024/    → one page per exam (LearningResource)
 *   courses/math-126/topics/double-integrals/    → one page per topic with questions (LearningResource)
 *   sitemap.xml                                  → home, privacy and every page above
 *
 * Problem text is not reproduced; exam pages list each problem's topic and skills
 * and link to the PDFs. Run `npm run build:pages` after changing exams.json,
 * questions.json or chapters.json and commit the output. CI fails if the
 * committed pages are out of date.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const SITE = 'https://uwmathfinder.com';
const read = f => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const exams = read('exams.json');
const questions = read('questions.json');
const chapters = read('chapters.json');
// use the same stylesheet version as index.html, so a release busts the cache here too
const CSS_V = (fs.readFileSync(path.join(root, 'index.html'), 'utf8').match(/styles\.css\?v=([\w.]+)/) || [])[1] || '1';

const COURSE_TITLES = {
  'Math 120': 'Precalculus',
  'Math 124': 'Calculus I',
  'Math 125': 'Calculus II',
  'Math 126': 'Calculus III',
  'Math 207': 'Differential Equations',
  'Math 208': 'Linear Algebra',
  'Math 224': 'Advanced Multivariable Calculus',
};
const TYPES = ['Midterm 1', 'Midterm 2', 'Final'];
const QUARTER_ORDER = { Winter: 0, Spring: 1, Summer: 2, Autumn: 3 };
const UW = { '@type': 'CollegeOrUniversity', name: 'University of Washington', url: 'https://www.washington.edu/' };

/** Escape text for HTML. */
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
/** "Math 126" → "math-126"; "Midterm 1 Winter 2024" → "midterm-1-winter-2024" */
const slug = s => String(s).toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
/** A site-root-relative link, so pages work at uwmathfinder.com and on localhost. */
const href = p => '/' + String(p).replace(/^\//, '');
const has = f => f && f !== '#';
/** The instructor, unless the exam is only credited to "Staff". */
const named = e => (e.instructor && e.instructor !== 'Staff' ? e.instructor : '');

/** Newest first. */
const byDate = (a, b) => b.year - a.year || (QUARTER_ORDER[b.quarter] ?? 0) - (QUARTER_ORDER[a.quarter] ?? 0);

/** Shared page shell: same stylesheet, theme handling and header as index.html. */
function page({ title, description, canonical, body, jsonld = [] }) {
  const ld = jsonld.map(o => `  <script type="application/ld+json">${JSON.stringify({ '@context': 'https://schema.org', ...o }).replace(/</g, '\\u003c')}</script>\n`).join('');
  return `<!DOCTYPE html>
<!-- Generated by scripts/build-pages.js — do not edit by hand; run \`npm run build:pages\`. -->
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}" />
  <link rel="canonical" href="${canonical}" />
  <meta property="og:title" content="${esc(title)}" />
  <meta property="og:description" content="${esc(description)}" />
  <meta property="og:url" content="${canonical}" />
  <meta property="og:image" content="${SITE}/favicon.png" />
  <link rel="icon" type="image/png" href="/favicon.png" />
${ld}  <script>try { if (localStorage.getItem('theme') === 'light') document.documentElement.setAttribute('data-theme', 'light'); } catch (e) {}</script>
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600&family=Inter:wght@300;400;500;600&display=swap" rel="stylesheet" />
  <link rel="stylesheet" href="/assets/css/styles.css?v=${CSS_V}" />
</head>
<body>
<header>
  <a href="/" class="logo" aria-label="UWMathFinder home">UW<span>Math</span>Finder</a>
  <div class="header-actions"><a class="view-btn" href="/#generate">★ Generate a practice exam</a></div>
</header>
<main id="main" class="seo-page">
${body}
</main>
<footer>
  <div class="footer-left">UWMathFinder · built for Huskies <a class="footer-privacy" href="/privacy.html">Privacy</a></div>
  <div class="footer-authors">Exam material © University of Washington Department of Mathematics</div>
</footer>
</body>
</html>
`;
}

/** BreadcrumbList JSON-LD plus the matching visible trail. crumbs: [[name, path], …] */
function crumbs(list) {
  return {
    ld: { '@type': 'BreadcrumbList', itemListElement: list.map(([name, p], i) => ({ '@type': 'ListItem', position: i + 1, name, item: SITE + p })) },
    html: `<nav class="hero-eyebrow" aria-label="Breadcrumb">${list.map(([name, p], i) => i === list.length - 1 ? esc(name) : `<a href="${p}">${esc(name)}</a>`).join(' › ')}</nav>`,
  };
}

const courses = [...new Set(exams.map(e => e.course))].sort((a, b) => parseInt(a.replace(/\D/g, '')) - parseInt(b.replace(/\D/g, '')));
const coursePath = c => `/courses/${slug(c)}/`;
const courseTitle = c => `${c}${COURSE_TITLES[c] ? ` (${COURSE_TITLES[c]})` : ''}`;
const courseLd = c => ({ '@type': 'Course', name: courseTitle(c), courseCode: c, provider: UW, url: SITE + coursePath(c) });
const chapterName = (c, id) => (chapters.courses[c]?.chapters || []).find(ch => ch.id === id)?.name || id;

/** Every question in a course, including those cross-listed into it (also_in) under their listed chapter. */
const courseQuestions = c => [...questions.filter(q => q.course === c),
  ...questions.flatMap(q => (q.also_in || []).filter(x => x.course === c).map(x => ({ ...q, chapter: x.chapter })))];

// ── exam URLs: <type>-<quarter>-<year>, plus the instructor or label when a course has two such exams
const examPath = new Map();
for (const c of courses) {
  const list = exams.filter(e => e.course === c && !e.is_key).sort((a, b) => a.id.localeCompare(b.id));
  const base = e => slug(`${e.type} ${e.quarter} ${e.year}`);
  const count = {};
  list.forEach(e => { count[base(e)] = (count[base(e)] || 0) + 1; });
  const used = new Set();
  for (const e of list) {
    let s = base(e);
    if (count[s] > 1) {
      const who = named(e).split(/[,&]/)[0].trim().split(' ').pop();
      s += '-' + slug(e.label ? e.label.replace(/^Math \d+:\s*/, '') : [who || e.id, /^Honors/.test(e.note || '') ? 'honors' : ''].join(' '));
    }
    for (let i = 2; used.has(s); i++) s = s.replace(/-\d+$/, '') + '-' + i;
    used.add(s);
    examPath.set(e.id, `${coursePath(c)}exams/${s}/`);
  }
}
const topicPath = (c, id) => `${coursePath(c)}topics/${slug(id)}/`;
const examName = e => `${e.course} ${e.type}, ${e.quarter} ${e.year}`;
// question source.exam_id and exam id can differ in letter case
const examById = new Map(exams.map(e => [e.id.toLowerCase(), e]));
const examOf = q => examById.get(String(q.source?.exam_id).toLowerCase());

/** The PDF and answer-key links for one exam. */
function examLinks(e) {
  const pdf = has(e.pdf) ? `<a href="${href(e.pdf)}">Exam PDF</a>` : 'Exam PDF coming';
  const key = has(e.answer_key) ? ` · <a href="${href(e.answer_key)}">${e.answer_key_unofficial ? 'Unofficial worked solutions' : 'Answer key'}</a>` : '';
  return pdf + key;
}

/** The page for one course: exams grouped by type, plus every topic tested. */
function coursePage(course) {
  const list = exams.filter(e => e.course === course && !e.is_key);
  const qs = courseQuestions(course);
  const counts = {};
  qs.forEach(q => { counts[q.chapter] = (counts[q.chapter] || 0) + 1; });
  const ranked = Object.entries(counts).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  const bc = crumbs([['Home', '/'], ['Courses', '/courses/'], [course, coursePath(course)]]);

  const sections = TYPES.map(type => {
    const rows = list.filter(e => e.type === type).sort(byDate);
    if (!rows.length) return '';
    return `
  <section class="seo-section">
    <h2>${esc(course)} ${esc(type)} exams</h2>
    <ul class="seo-list">
${rows.map(e => {
  const topics = (e.topics || []).length ? `<span class="seo-topics">${e.topics.map(esc).join(', ')}</span>` : '';
  const who = [e.label, named(e)].filter(Boolean).map(esc).join(', ');
  return `      <li><a href="${examPath.get(e.id)}"><strong>${esc(e.quarter)} ${esc(e.year)}</strong></a>${who ? ` (${who})` : ''} — ${examLinks(e)} ${topics}</li>`;
}).join('\n')}
    </ul>
  </section>`;
  }).join('');

  const body = `
  <section class="hero">
    ${bc.html}
    <h1>${esc(courseTitle(course))} <em>past exams</em></h1>
    <p class="hero-sub">${list.length} archived ${esc(course)} midterms and finals with answer keys, and ${qs.length} individual practice problems tagged by topic.</p>
    <div class="hero-cta">
      <a class="gen-btn gold" href="/#generate">★ Generate a ${esc(course)} practice exam</a>
      <a class="gen-btn ghost" href="/#questions">❖ Practice ${esc(course)} by topic</a>
    </div>
  </section>
  ${ranked.length ? `<section class="seo-section">
    <h2>${esc(course)} topics, most tested first</h2>
    <ol class="seo-list">
${ranked.map(([id, n]) => `      <li><a href="${topicPath(course, id)}">${esc(chapterName(course, id))}</a> — ${n} past questions</li>`).join('\n')}
    </ol>
  </section>` : ''}${sections}`;

  return page({
    title: `${courseTitle(course)} Past Exams & Answer Keys — UW | UWMathFinder`,
    description: `Past University of Washington ${courseTitle(course)} midterms and finals with answer keys, the most-tested topics, and a free practice exam generator.`,
    canonical: SITE + coursePath(course),
    body,
    jsonld: [{ ...courseLd(course), description: `Past ${courseTitle(course)} exams and answer keys from the University of Washington.` }, bc.ld],
  });
}

/** The page for one exam: who set it, the links, and what each problem tests. */
function examPage(e) {
  const p = examPath.get(e.id);
  const name = examName(e);
  const who = named(e);
  const qs = questions.filter(q => examOf(q) === e).sort((a, b) => (a.source.problem ?? 0) - (b.source.problem ?? 0));
  const bc = crumbs([['Home', '/'], ['Courses', '/courses/'], [e.course, coursePath(e.course)], [`${e.type}, ${e.quarter} ${e.year}`, p]]);
  const keyWord = has(e.answer_key) ? (e.answer_key_unofficial ? 'unofficial worked solutions' : 'answer key') : '';
  const facts = [
    who && `<li><strong>${e.type === 'Final' ? 'Instructors' : 'Instructor'}:</strong> ${esc(who)}</li>`,
    e.label && `<li><strong>Exam:</strong> ${esc(e.label)}</li>`,
    `<li><strong>Files:</strong> ${examLinks(e)}</li>`,
    (e.topics || []).length && `<li><strong>Topics:</strong> ${e.topics.map(esc).join(', ')}</li>`,
    e.source_url && `<li><strong>Source:</strong> <a href="${esc(e.source_url)}" rel="nofollow">${esc(e.source_url.replace(/^https?:\/\//, ''))}</a></li>`,
  ].filter(Boolean).join('\n      ');
  const note = [e.note, e.answer_key_unofficial && 'The worked solutions were written by UWMathFinder, not the instructor; report any error on the site.'].filter(Boolean).map(esc).join(' ');

  const body = `
  <section class="hero">
    ${bc.html}
    <h1>${esc(name)} <em>past exam${keyWord ? ' & ' + esc(keyWord) : ''}</em></h1>
    <p class="hero-sub">University of Washington ${esc(courseTitle(e.course))}${who ? `, ${esc(who)}` : ''}.${note ? ' ' + note : ''}</p>
    <div class="hero-cta">
      ${has(e.pdf) ? `<a class="gen-btn gold" href="${href(e.pdf)}">Open the exam PDF</a>` : ''}
      <a class="gen-btn ghost" href="/#generate">★ Generate a ${esc(e.course)} practice exam</a>
    </div>
  </section>
  <section class="seo-section">
    <ul class="seo-list">
      ${facts}
    </ul>
  </section>
  ${qs.length ? `<section class="seo-section">
    <h2>What each problem tests</h2>
    <ol class="seo-list">
${qs.map(q => `      <li value="${esc(q.source.problem)}"><a href="${topicPath(q.course, q.chapter)}">${esc(chapterName(q.course, q.chapter))}</a>${q.points ? ` · ${esc(q.points)} pts` : ''}${(q.skills || []).length ? `<span class="seo-topics">${q.skills.map(esc).join(', ')}</span>` : ''}</li>`).join('\n')}
    </ol>
  </section>` : ''}
  <section class="seo-section">
    <p class="seo-list">More <a href="${coursePath(e.course)}">${esc(e.course)} past exams</a>.</p>
  </section>`;

  return page({
    title: `${name} — Past Exam${keyWord ? ' & ' + (e.answer_key_unofficial ? 'Worked Solutions' : 'Answer Key') : ''} | UWMathFinder`,
    description: `${name} from the University of Washington${who ? ` (${who})` : ''}: exam PDF${keyWord ? `, ${keyWord}` : ''} and the topic of every problem${(e.topics || []).length ? `: ${e.topics.slice(0, 4).join(', ')}` : ''}.`,
    canonical: SITE + p,
    body,
    jsonld: [{
      '@type': 'LearningResource',
      name,
      url: SITE + p,
      learningResourceType: 'Exam',
      educationalLevel: 'Undergraduate',
      inLanguage: 'en',
      about: (e.topics || []).map(t => ({ '@type': 'Thing', name: t })),
      ...(who && { author: who.split(/,\s*/).map(n => ({ '@type': 'Person', name: n })) }),
      dateCreated: String(e.year),
      ...(e.source_url && { isBasedOn: e.source_url }),
      ...(has(e.pdf) && { associatedMedia: { '@type': 'MediaObject', contentUrl: SITE + href(e.pdf), encodingFormat: 'application/pdf' } }),
      isPartOf: courseLd(e.course),
      publisher: UW,
    }, bc.ld],
  });
}

/** The page for one topic: every past problem on it, linked to its exam. */
function topicPage(course, id, qs) {
  const p = topicPath(course, id);
  const name = chapterName(course, id);
  const ch = (chapters.courses[course]?.chapters || []).find(x => x.id === id) || {};
  const bc = crumbs([['Home', '/'], ['Courses', '/courses/'], [course, coursePath(course)], [name, p]]);
  const rows = qs.map(q => ({ q, e: examOf(q) })).filter(r => r.e)
    .sort((a, b) => byDate(a.e, b.e) || TYPES.indexOf(a.e.type) - TYPES.indexOf(b.e.type) || (a.q.source.problem ?? 0) - (b.q.source.problem ?? 0));
  const skills = {};
  rows.forEach(({ q }) => (q.skills || []).forEach(s => { const k = Object.keys(skills).find(x => x.toLowerCase() === s.toLowerCase()) || s; skills[k] = (skills[k] || 0) + 1; }));
  const topSkills = Object.entries(skills).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 8).map(([s]) => s);
  const types = (ch.types || []).join(', ').replace(/, ([^,]*)$/, ' and $1');

  const body = `
  <section class="hero">
    ${bc.html}
    <h1>${esc(name)} <em>${esc(course)} past exam problems</em></h1>
    <p class="hero-sub">${rows.length} past University of Washington exam problems on ${esc(name)}${(ch.sections || []).length ? ` (textbook ${ch.sections.length > 1 ? 'sections' : 'section'} ${ch.sections.map(esc).join(', ')})` : ''}${types ? `, usually tested on the ${esc(types)} exams` : ''}.</p>
    <div class="hero-cta">
      <a class="gen-btn gold" href="/#questions">❖ Practice ${esc(name)} problems</a>
      <a class="gen-btn ghost" href="/#generate">★ Generate a ${esc(course)} practice exam</a>
    </div>
  </section>
  ${topSkills.length ? `<section class="seo-section">
    <h2>Skills tested most</h2>
    <p class="seo-list">${topSkills.map(esc).join(' · ')}</p>
  </section>` : ''}
  <section class="seo-section">
    <h2>Every past ${esc(name)} problem</h2>
    <ul class="seo-list">
${rows.map(({ q, e }) => {
  const who = named(e);
  return `      <li><a href="${examPath.get(e.id)}">${esc(e.course !== course ? e.course + ' ' : '')}${esc(e.type)}, ${esc(e.quarter)} ${esc(e.year)}</a> · Problem ${esc(q.source.problem)}${who ? ` · ${esc(who)}` : ''}${(q.skills || []).length ? `<span class="seo-topics">${q.skills.map(esc).join(', ')}</span>` : ''}</li>`;
}).join('\n')}
    </ul>
  </section>
  <section class="seo-section">
    <p class="seo-list">More <a href="${coursePath(course)}">${esc(course)} topics and past exams</a>.</p>
  </section>`;

  return page({
    title: `${name} — ${course} Past Exam Problems (UW) | UWMathFinder`,
    description: `${rows.length} past University of Washington ${course} exam problems on ${name}, with the exam, instructor and skills for each${topSkills.length ? `: ${topSkills.slice(0, 4).join(', ')}` : ''}.`,
    canonical: SITE + p,
    body,
    jsonld: [{
      '@type': 'LearningResource',
      name: `${name} — ${course} past exam problems`,
      url: SITE + p,
      learningResourceType: 'Practice problems',
      educationalLevel: 'Undergraduate',
      inLanguage: 'en',
      about: [{ '@type': 'Thing', name }, ...topSkills.map(s => ({ '@type': 'Thing', name: s }))],
      teaches: name,
      isPartOf: courseLd(course),
      publisher: UW,
    }, bc.ld],
  });
}

/** The index of all course pages. */
function indexPage() {
  const bc = crumbs([['Home', '/'], ['Courses', '/courses/']]);
  const body = `
  <section class="hero">
    ${bc.html}
    <h1>Past UW math exams <em>by course</em></h1>
    <p class="hero-sub">Midterms and finals with answer keys for every course we cover.</p>
  </section>
  <section class="seo-section">
    <ul class="seo-list">
${courses.map(c => `      <li><a href="${coursePath(c)}"><strong>${esc(c)}</strong>${COURSE_TITLES[c] ? ' — ' + esc(COURSE_TITLES[c]) : ''}</a> · ${exams.filter(e => e.course === c && !e.is_key).length} exams</li>`).join('\n')}
    </ul>
  </section>`;
  return page({
    title: 'Past UW Math Exams by Course | UWMathFinder',
    description: `Browse past University of Washington math midterms and finals with answer keys for ${courses.join(', ').replace(/, ([^,]*)$/, ' and $1')}.`,
    canonical: `${SITE}/courses/`,
    body,
    jsonld: [{ '@type': 'ItemList', itemListElement: courses.map((c, i) => ({ '@type': 'ListItem', position: i + 1, url: SITE + coursePath(c), name: courseTitle(c) })) }, bc.ld],
  });
}

/** Write a file, creating folders as needed. */
function write(rel, content) {
  const file = path.join(root, rel.replace(/^\//, ''));
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

// start clean, so renamed or removed exams and topics don't leave stale pages behind
fs.rmSync(path.join(root, 'courses'), { recursive: true, force: true });
write('courses/index.html', indexPage());
const urls = [
  { loc: `${SITE}/`, freq: 'weekly', pri: '1.0' },
  { loc: `${SITE}/courses/`, freq: 'weekly', pri: '0.8' },
];
let nExam = 0, nTopic = 0;
for (const c of courses) {
  write(`${coursePath(c)}index.html`, coursePage(c));
  urls.push({ loc: SITE + coursePath(c), freq: 'weekly', pri: '0.8' });
  const byChapter = new Map();
  courseQuestions(c).forEach(q => byChapter.set(q.chapter, [...(byChapter.get(q.chapter) || []), q]));
  for (const [id, qs] of [...byChapter].sort()) {
    write(`${topicPath(c, id)}index.html`, topicPage(c, id, qs));
    urls.push({ loc: SITE + topicPath(c, id), freq: 'monthly', pri: '0.6' });
    nTopic++;
  }
  for (const e of exams.filter(x => x.course === c && !x.is_key).sort(byDate)) {
    write(`${examPath.get(e.id)}index.html`, examPage(e));
    urls.push({ loc: SITE + examPath.get(e.id), freq: 'monthly', pri: '0.5' });
    nExam++;
  }
}
urls.push({ loc: `${SITE}/privacy.html`, freq: 'yearly', pri: '0.3' });
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-pages.js -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url>\n    <loc>${u.loc}</loc>\n    <changefreq>${u.freq}</changefreq>\n    <priority>${u.pri}</priority>\n  </url>`).join('\n')}
</urlset>
`);
console.log(`✓ Wrote ${courses.length} course pages, ${nTopic} topic pages, ${nExam} exam pages, and sitemap.xml (${urls.length} URLs)`);
