#!/usr/bin/env node
/**
 * build-pages.js — generate static, search-engine-friendly course pages.
 *
 * The main site renders everything with JavaScript, which search engines index
 * poorly. This script writes plain HTML pages that list every exam for a course,
 * so a search like "UW Math 126 past finals" can land on uwmathfinder.com:
 *
 *   courses/index.html             → all courses
 *   courses/math-126/index.html    → one page per course
 *   sitemap.xml                    → home, privacy and every course page
 *
 * Run `npm run build:pages` after changing exams.json or questions.json and commit
 * the output. CI fails if the committed pages are out of date.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const SITE = 'https://uwmathfinder.com';
const read = f => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const exams = read('exams.json');
const questions = read('questions.json');
const chapters = read('chapters.json');

const COURSE_TITLES = {
  'Math 120': 'Precalculus',
  'Math 124': 'Calculus I',
  'Math 125': 'Calculus II',
  'Math 126': 'Calculus III',
  'Math 207': 'Differential Equations',
  'Math 208': 'Linear Algebra',
};
const TYPES = ['Midterm 1', 'Midterm 2', 'Final'];
const QUARTER_ORDER = { Winter: 0, Spring: 1, Summer: 2, Autumn: 3 };

/** Escape text for HTML. */
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
/** "Math 126" → "math-126" */
const slug = course => course.toLowerCase().replace(/\s+/g, '-');
/** A site-root-relative link, so pages work at uwmathfinder.com and on localhost. */
const href = p => '/' + String(p).replace(/^\//, '');

/** Shared page shell: same stylesheet, theme handling and header as index.html. */
function page({ title, description, canonical, body }) {
  return `<!DOCTYPE html>
<!-- Generated by scripts/build-pages.js — do not edit by hand; run \`npm run build:pages\`. -->
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}" />
  <link rel="canonical" href="${canonical}" />
  <meta property="og:title" content="${esc(title)}" />
  <meta property="og:description" content="${esc(description)}" />
  <meta property="og:url" content="${canonical}" />
  <meta property="og:image" content="${SITE}/favicon.png" />
  <link rel="icon" type="image/png" href="/favicon.png" />
  <script>try { if (localStorage.getItem('theme') === 'light') document.documentElement.setAttribute('data-theme', 'light'); } catch (e) {}</script>
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600&family=Inter:wght@300;400;500;600&display=swap" rel="stylesheet" />
  <link rel="stylesheet" href="/assets/css/styles.css?v=0.13" />
</head>
<body>
<header>
  <a href="/" class="logo" aria-label="UWMathFinder home">UW<span>Math</span>Finder</a>
  <div class="header-actions"><a class="view-btn" href="/#generate">★ Generate a practice exam</a></div>
</header>
<main id="main" class="seo-page">
${body}
</main>
<footer>
  <div class="footer-left">UWMathFinder · built for Huskies <a class="footer-privacy" href="/privacy.html">Privacy</a></div>
  <div class="footer-authors">Exam material © University of Washington Department of Mathematics</div>
</footer>
</body>
</html>
`;
}

/** Newest exams first. */
const byDate = (a, b) => b.year - a.year || (QUARTER_ORDER[b.quarter] ?? 0) - (QUARTER_ORDER[a.quarter] ?? 0);

/** The page for one course: exams grouped by type, plus the most-tested topics. */
function coursePage(course) {
  const list = exams.filter(e => e.course === course && !e.is_key);
  const qs = questions.filter(q => q.course === course);
  const names = new Map((chapters.courses[course]?.chapters || []).map(c => [c.id, c.name]));
  const subject = COURSE_TITLES[course] ? ` (${COURSE_TITLES[course]})` : '';

  // rank chapters by how many archived questions test them
  const counts = {};
  qs.forEach(q => { counts[q.chapter] = (counts[q.chapter] || 0) + 1; });
  const top = Object.entries(counts).sort((a, b) => b[1] - a[1]).slice(0, 10);

  const sections = TYPES.map(type => {
    const rows = list.filter(e => e.type === type).sort(byDate);
    if (!rows.length) return '';
    return `
  <section class="seo-section">
    <h2>${esc(course)} ${esc(type)} exams</h2>
    <ul class="seo-list">
${rows.map(e => {
  const pdf = e.pdf && e.pdf !== '#' ? `<a href="${href(e.pdf)}">Exam PDF</a>` : 'Exam PDF coming';
  const key = e.answer_key && e.answer_key !== '#' ? ` · <a href="${href(e.answer_key)}">Answer key</a>` : '';
  const topics = (e.topics || []).length ? `<span class="seo-topics">${e.topics.map(esc).join(', ')}</span>` : '';
  return `      <li><strong>${esc(e.quarter)} ${esc(e.year)}</strong> — ${pdf}${key} ${topics}</li>`;
}).join('\n')}
    </ul>
  </section>`;
  }).join('');

  const body = `
  <section class="hero">
    <div class="hero-eyebrow"><a href="/courses/">All courses</a> · University of Washington</div>
    <h1>${esc(course)}${esc(subject)} <em>past exams</em></h1>
    <p class="hero-sub">${list.length} archived ${esc(course)} midterms and finals with answer keys, and ${qs.length} individual practice problems tagged by topic.</p>
    <div class="hero-cta">
      <a class="gen-btn gold" href="/#generate">★ Generate a ${esc(course)} practice exam</a>
      <a class="gen-btn ghost" href="/#questions">❖ Practice ${esc(course)} by topic</a>
    </div>
  </section>
  ${top.length ? `<section class="seo-section">
    <h2>Most-tested ${esc(course)} topics</h2>
    <ol class="seo-list">
${top.map(([id, n]) => `      <li>${esc(names.get(id) || id)} — ${n} past questions</li>`).join('\n')}
    </ol>
  </section>` : ''}${sections}`;

  return page({
    title: `${course}${subject} Past Exams & Answer Keys — UW | UWMathFinder`,
    description: `Past University of Washington ${course}${subject} midterms and finals with answer keys, the most-tested topics, and a free practice exam generator.`,
    canonical: `${SITE}/courses/${slug(course)}/`,
    body,
  });
}

/** The index of all course pages. */
function indexPage(courses) {
  const body = `
  <section class="hero">
    <div class="hero-eyebrow">University of Washington · Mathematics</div>
    <h1>Past UW math exams <em>by course</em></h1>
    <p class="hero-sub">Midterms and finals with answer keys for every course we cover.</p>
  </section>
  <section class="seo-section">
    <ul class="seo-list">
${courses.map(c => `      <li><a href="/courses/${slug(c)}/"><strong>${esc(c)}</strong>${COURSE_TITLES[c] ? ' — ' + esc(COURSE_TITLES[c]) : ''}</a> · ${exams.filter(e => e.course === c && !e.is_key).length} exams</li>`).join('\n')}
    </ul>
  </section>`;
  return page({
    title: 'Past UW Math Exams by Course | UWMathFinder',
    description: 'Browse past University of Washington math midterms and finals with answer keys for Math 120, 124, 125, 126, 207 and 208.',
    canonical: `${SITE}/courses/`,
    body,
  });
}

/** Write a file, creating folders as needed. */
function write(rel, content) {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

const courses = [...new Set(exams.map(e => e.course))].sort();
write('courses/index.html', indexPage(courses));
courses.forEach(c => write(`courses/${slug(c)}/index.html`, coursePage(c)));

const urls = [
  { loc: `${SITE}/`, freq: 'weekly', pri: '1.0' },
  { loc: `${SITE}/courses/`, freq: 'weekly', pri: '0.8' },
  ...courses.map(c => ({ loc: `${SITE}/courses/${slug(c)}/`, freq: 'weekly', pri: '0.8' })),
  { loc: `${SITE}/privacy.html`, freq: 'yearly', pri: '0.3' },
];
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-pages.js -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url>\n    <loc>${u.loc}</loc>\n    <changefreq>${u.freq}</changefreq>\n    <priority>${u.pri}</priority>\n  </url>`).join('\n')}
</urlset>
`);
console.log(`✓ Wrote courses/index.html, ${courses.length} course pages, and sitemap.xml`);
