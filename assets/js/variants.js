/**
 * variants.js — the "New Problems" tab: brand-new practice problems generated from
 * templates of real UW exam questions (data in variants/*.json, written and
 * answer-checked by scripts/variants/build.py).
 *
 * Loaded after app.js and uses its helpers (esc, courseClass, track, REPO_URL).
 * KaTeX and the problem data are only downloaded the first time the tab opens.
 */
const Variants = (() => {
  const KATEX = 'https://cdnjs.cloudflare.com/ajax/libs/KaTeX/0.16.9/';
  const el = id => document.getElementById(id);
  let index = null;            // variants/index.json
  const courses = new Map();   // course -> loaded course file
  let current = null;          // { course, template, variant }
  let ready = null;

  /** Load a script or stylesheet once. */
  function load(url, css) {
    return new Promise((resolve, reject) => {
      const tag = document.createElement(css ? 'link' : 'script');
      if (css) { tag.rel = 'stylesheet'; tag.href = url; } else { tag.src = url; tag.defer = true; }
      tag.onload = resolve;
      tag.onerror = () => reject(new Error('Could not load ' + url));
      document.head.appendChild(tag);
    });
  }

  /** First open: KaTeX + the index of courses and topics. */
  function init() {
    if (!ready) {
      ready = Promise.all([
        load(KATEX + 'katex.min.css', true),
        load(KATEX + 'katex.min.js').then(() => load(KATEX + 'contrib/auto-render.min.js')),
        fetch('variants/index.json').then(r => r.json()).then(j => { index = j.courses; }),
      ]).then(() => {
        const list = Object.keys(index);
        el('newCourse').innerHTML = list.map(c => `<option value="${esc(c)}">${esc(c)}</option>`).join('');
        el('newCourse').addEventListener('change', () => { fillTopics(); next(); });
        el('newTopic').addEventListener('change', next);
        el('newNext').addEventListener('click', next);
        el('newOut').addEventListener('click', onClick);
        fillTopics();
        return next();
      }).catch(err => {
        ready = null;
        el('newOut').innerHTML = `<div class="empty"><h3>Couldn't load the practice problems</h3><p>${esc(err.message)}. Check your connection and try again.</p></div>`;
      });
    }
    return ready;
  }

  function fillTopics() {
    const c = index[el('newCourse').value];
    el('newTopic').innerHTML = `<option value="">All topics</option>` +
      c.topics.map(t => `<option value="${esc(t.chapter)}">${esc(t.name)}</option>`).join('');
    el('newInfo').textContent = `${c.variants} checked problems from ${c.templates} templates`;
  }

  async function courseData(course) {
    if (!courses.has(course)) {
      courses.set(course, await fetch(index[course].file).then(r => r.json()));
    }
    return courses.get(course);
  }

  /** Show a random problem for the chosen course/topic, never the same one twice in a row. */
  async function next() {
    const course = el('newCourse').value;
    const topic = el('newTopic').value;
    const data = await courseData(course);
    const ts = data.templates.filter(t => !topic || t.chapter === topic);
    const t = ts[Math.floor(Math.random() * ts.length)];
    let v = t.variants[Math.floor(Math.random() * t.variants.length)];
    if (current && v.id === current.variant.id && t.variants.length > 1) {
      v = t.variants[(t.variants.indexOf(v) + 1) % t.variants.length];
    }
    current = { course, template: t, variant: v };
    render();
    track('new_problem', { course, template: t.id });
  }

  function basedOn(b) {
    if (b.style) return `in the style of ${esc(b.style)}`;
    return `modelled on <a href="${esc(b.pdf)}" target="_blank" rel="noopener">${esc(b.label)}</a>`;
  }

  function render() {
    const { course, template: t, variant: v } = current;
    const report = `${REPO_URL}/issues/new?` + new URLSearchParams({
      title: `Mistake in practice problem ${v.id}`,
      body: `Practice problem: ${v.id} (${course}, ${t.title})\n\nWhat's wrong:\n`,
    });
    el('newOut').innerHTML = `
      <article class="q-card variant-card">
        <div class="q-meta">
          <span class="course-badge ${courseClass(course)}">${esc(course)}</span>
          <span class="q-chapter">${esc(t.chapter_name)}</span>
          <span class="variant-tag" title="A new problem generated by UWMathFinder, not a past exam question">Practice variant</span>
          <span class="q-source">${basedOn(t.based_on)}</span>
        </div>
        <h3 class="variant-title">${esc(t.title)}</h3>
        <div class="variant-body">${v.problem}</div>
        <div class="variant-answer" id="newAnswer" hidden><div class="variant-label">Answer</div>${v.answer}</div>
        <div class="variant-solution" id="newSolution" hidden><div class="variant-label">Worked solution</div>${v.solution}</div>
        <div class="q-actions">
          <button type="button" class="key-btn" data-action="answer" aria-expanded="false" aria-controls="newAnswer">✦ Show answer</button>
          <button type="button" class="key-btn" data-action="solution" aria-expanded="false" aria-controls="newSolution">✦ Show worked solution</button>
          <a class="q-link" href="${report}" target="_blank" rel="noopener">Report a mistake</a>
        </div>
      </article>`;
    typeset(el('newOut'));
  }

  function typeset(node) {
    window.renderMathInElement(node, {
      delimiters: [{ left: '\\[', right: '\\]', display: true }, { left: '$', right: '$', display: false }],
      throwOnError: false,
    });
  }

  function onClick(e) {
    const btn = e.target.closest('button[data-action]');
    if (!btn) return;
    const box = el(btn.dataset.action === 'answer' ? 'newAnswer' : 'newSolution');
    box.hidden = !box.hidden;
    btn.setAttribute('aria-expanded', String(!box.hidden));
    const what = btn.dataset.action === 'answer' ? 'answer' : 'worked solution';
    btn.textContent = `✦ ${box.hidden ? 'Show' : 'Hide'} ${what}`;
    if (!box.hidden) track('show_variant_' + btn.dataset.action, { template: current.template.id });
  }

  return { open: init };
})();

// app.js may have opened this tab (from the URL hash) before this file ran
if (!document.getElementById('viewNew').hidden) Variants.open();
